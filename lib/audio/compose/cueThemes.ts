import type { MusicCue } from "./types";
import type { MotifPhrase } from "./missionThemes";

export type CueMotifBook = {
  verse: readonly MotifPhrase[];
  hook: readonly MotifPhrase[];
};

function book(
  verse: readonly (readonly [readonly (number | null)[], readonly number[]])[],
  hook: readonly (readonly [readonly (number | null)[], readonly number[]])[],
): CueMotifBook {
  const phrases = (rows: typeof verse) => rows.map(([degrees, rhythm]) => ({ degrees, rhythm }));
  return { verse: phrases(verse), hook: phrases(hook) };
}

